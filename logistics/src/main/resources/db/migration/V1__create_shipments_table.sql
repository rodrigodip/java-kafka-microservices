-- ================================================================ --
-- PENDING -> Order invoiced and waiting for shipment
-- SHIPPED -> Tracking code registered and order shipped
-- ================================================================ --

CREATE TABLE shipments(
    id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id BIGINT NOT NULL UNIQUE,
    client_id BIGINT NOT NULL,
    client_name VARCHAR(150),
    client_cpf VARCHAR(11),
    client_email VARCHAR(100),
    client_phone VARCHAR(20),
    client_address VARCHAR(100),
    client_address_number VARCHAR(10),
    client_zipcode VARCHAR(8),
    status VARCHAR(20) NOT NULL DEFAULT 'PENDING' CHECK (
        status in ('PENDING', 'SHIPPED')
    ),
    total NUMERIC(16,2) NOT NULL,
    invoice_url TEXT,
    tracking_code VARCHAR(255),
    created_at TIMESTAMP NOT NULL DEFAULT now(),
    shipped_at TIMESTAMP
);

CREATE INDEX idx_shipments__status ON shipments(status);
CREATE INDEX idx_shipments__client_id ON shipments(client_id);

CREATE TABLE shipment_items(
    id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    shipment_id INT NOT NULL REFERENCES shipments (id),
    product_id BIGINT NOT NULL,
    name VARCHAR(150),
    quantity INT NOT NULL,
    unit_price NUMERIC(16,2) NOT NULL
);

CREATE INDEX idx_shipment_items__shipment_id ON shipment_items(shipment_id);
